"""Smoke test for the compiled ``openwq_py`` pybind11 bridge.

The module is built into src/lisflood/openwq/ (see README, step 2), so it is
looked up there. Skipped only when it has not been built. The lifecycle test
uses the inputs generated by openWQ's template generator (README, step 1) and is
skipped if they have not been generated.
"""
import os
import sys
from pathlib import Path

import numpy as np
import pytest

PKG = Path(__file__).resolve().parent.parent          # src/lisflood/openwq
sys.path.insert(0, str(PKG))
openwq_py = pytest.importorskip(
    "openwq_py", reason="openwq_py not built yet; run the CMake build (README step 2)")

CASE = Path(os.environ.get("OWQ_CASE_DIR",
                           PKG / "tests" / "_case_nitrogen_simple")).resolve()


def test_host_api_present():
    for method in ("add_compartment", "add_ext_flux", "add_depend", "init",
                   "set_water_volume_array", "set_depend_array", "time_start",
                   "move", "move_array", "inflow", "time_end", "mass_array"):
        assert hasattr(openwq_py.Host, method), f"Host.{method} missing"


def test_lifecycle_on_generated_inputs(tmp_path):
    if not (CASE / "openWQ_master.json").exists():
        pytest.skip("generate the inputs first (README step 1)")
    import shutil
    from lisflood.openwq.coupler import COMPARTMENTS, ewf_names_from_master
    run = tmp_path / "run"
    shutil.copytree(CASE, run, ignore=shutil.ignore_patterns("openwq_out"))
    prev = os.getcwd()
    os.chdir(run)
    try:
        H = openwq_py.Host("openWQ_master.json")
        ic = {c: H.add_compartment(c, 2, 1, 1) for c in COMPARTMENTS}
        for name in ewf_names_from_master(run / "openWQ_master.json"):
            H.add_ext_flux(name, 2, 1, 1)
        iT = H.add_depend("T", 2, 1, 1)
        H.init()
        for c in COMPARTMENTS:
            H.set_water_volume_array(ic[c], np.full(2, 100.0))
        H.set_depend_array(iT, np.full(2, 15.0))
        H.time_start(2000, 1, 1)
        H.time_end(2000, 1, 1)
        assert H.num_species() >= 1
        assert np.all(np.asarray(H.mass_array(ic["CHANNEL"], 0)) > 0)   # ICs seeded
    finally:
        os.chdir(prev)
